// Build src/plates.js: ANIM.PLATES = { id: dataURI } from art/plates/<ID>.jpg (full-res)
// falling back to art/preview/<ID>.png (600px dev previews). Run before build.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const man = JSON.parse(fs.readFileSync(path.join(root, 'art/manifest.json'), 'utf8'));
const out = {}; const info = [];
for (const id of Object.keys(man.plates)) {
  const full = path.join(root, 'art/plates', id + '.jpg'), prev = path.join(root, 'art/preview', id + '.png');
  let p = null, mime = null;
  if (fs.existsSync(full)) { p = full; mime = 'image/jpeg'; } else if (fs.existsSync(prev)) { p = prev; mime = 'image/png'; }
  if (!p) { info.push(`${id}: MISSING`); continue; }
  const b = fs.readFileSync(p); out[id] = `data:${mime};base64,${b.toString('base64')}`; info.push(`${id}: ${path.basename(p)} ${(b.length / 1024).toFixed(0)}KB`);
}
fs.writeFileSync(path.join(root, 'src/plates.js'), `/* generated by tools/plates.js — do not edit */\nANIM.PLATES = ${JSON.stringify(out)};\n`);
console.log(info.join('\n')); console.log('src/plates.js written,', Object.keys(out).length, 'plates');
